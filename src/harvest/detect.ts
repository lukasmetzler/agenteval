/** Trailers agents add that link a commit to its agent session. */
const SESSION_TRAILERS: { pattern: RegExp; tool: string }[] = [
	{ pattern: /^Agent-Logs-Url:/im, tool: "copilot" },
	{ pattern: /^Amp-Thread-ID:/im, tool: "amp" },
];

/** Commit message patterns that suggest AI involvement. */
const MESSAGE_PATTERNS =
	/generated by|generated with|co-authored-by.*(?:claude|copilot|cursor|gemini|codex)|🤖|bot:|auto-generated|ai-generated/i;
const MESSAGE_TOOLS: { pattern: RegExp; tool: string }[] = [
	{ pattern: /generated with \[?claude code/i, tool: "claude" },
	{ pattern: /generated with \[?codex/i, tool: "codex" },
];

// Fields are NUL-separated; records end with \x1D because the body can span lines.
export const GIT_LOG_FORMAT =
	"%H%x00%h%x00%s%x00%ae%x00%aI%x00%(trailers:key=Co-authored-by,valueonly,separator=%x1E)%x00%an%x00%b%x1D";

/**
 * Parse git log output into structured commits. Accepts the record format of
 * GIT_LOG_FORMAT (\x1D-terminated, with author name and body) and the older
 * one-commit-per-line format without them.
 */
export function parseGitLog(output: string): RawCommit[] {
	const records = output.includes("\x1D") ? output.split("\x1D") : output.trim().split("\n");
	const commits: RawCommit[] = [];

	for (const record of records) {
		const line = record.replace(/^\n/, "");
		if (!line.trim()) continue;

		const fields = line.split("\0");
		if (fields.length < 5) continue;

		commits.push({
			hash: fields[0] ?? "",
			shortHash: fields[1] ?? "",
			subject: fields[2] ?? "",
			authorEmail: fields[3] ?? "",
			date: fields[4] ?? "",
			coAuthorRaw: fields[5] ?? "",
			authorName: fields[6],
			body: fields[7],
		});
	}

	return commits;
}

/**
 * Parse co-author trailer values into individual entries.
 * Input format: "Name <email>" separated by \x1E (record separator).
 */
function parseCoAuthors(raw: string): { name: string; email: string }[] {
	if (!raw.trim()) return [];

	return raw.split("\x1E").flatMap((entry) => {
		const trimmed = entry.trim();
		if (!trimmed) return [];
		const match = /^(.+?)\s*<(.+?)>/.exec(trimmed);
		if (!match?.[1] || !match[2]) {
			process.stderr.write(`Warning: malformed co-author trailer: "${trimmed}"\n`);
			return [];
		}
		return [{ name: match[1].trim(), email: match[2].trim() }];
	});
}

interface Match {
	tool: string;
	model?: string;
}

/** Model named in an attribution, e.g. "Claude Opus 5.5" or "aider (gpt-5)". */
function modelFromName(tool: string, name: string): string | undefined {
	if (tool === "claude" && !/^claude( code)?$/i.test(name)) return name;
	if (tool === "aider") return /\((.+)\)/.exec(name)?.[1];
	return undefined;
}

function matchCoAuthorAI(coAuthors: { name: string; email: string }[]): Match | null {
	for (const author of coAuthors) {
		for (const sig of SIGNATURES) {
			const emailHit = sig.coAuthorEmail?.test(author.email) ?? false;
			const nameHit = sig.coAuthorName?.test(author.name) ?? false;
			if ((emailHit && (!sig.nameRequired || nameHit)) || (nameHit && !sig.nameRequired)) {
				return { tool: sig.tool, model: modelFromName(sig.tool, author.name) };
			}
		}
	}
	return null;
}

/** Commit authored by an agent's own account (bot email or tool-specific name). */
function matchAuthorAI(commit: RawCommit): Match | null {
	for (const sig of SIGNATURES) {
		const name = commit.authorName ?? "";
		if (sig.authorEmail?.test(commit.authorEmail) || (name && sig.authorName?.test(name))) {
			// Author names carry no model ("Jane Doe (aider)"), unlike co-author trailers.
			return { tool: sig.tool };
		}
	}
	return null;
}

function matchMessage(commit: RawCommit): Match | null {
	const message = `${commit.subject}\n${commit.body ?? ""}`;
	for (const { pattern, tool } of SESSION_TRAILERS) {
		if (pattern.test(message)) return { tool };
	}
	return null;
}

/**
 * Detect AI signals on a single commit. Returns detection method, confidence,
 * tool, and model when the attribution names one, or null if no AI signal.
 */
export function detectSignals(
	commit: RawCommit,
): { method: DetectionMethod; confidence: number; tool: string; model?: string } | null {
	// 1. Co-author trailer or agent session trailer (confidence 0.9)
	const coAuthor = matchCoAuthorAI(parseCoAuthors(commit.coAuthorRaw)) ?? matchMessage(commit);
	if (coAuthor) return { method: "co-author-tag", confidence: 0.9, ...coAuthor };

	// 2. Commit authored by the agent's own account (confidence 0.8)
	const author = matchAuthorAI(commit);
	if (author) return { method: "author-email", confidence: 0.8, ...author };

	// 3. Message pattern in subject or body (confidence 0.6)
	const message = `${commit.subject}\n${commit.body ?? ""}`;
	if (MESSAGE_PATTERNS.test(message)) {
		const tool = MESSAGE_TOOLS.find((m) => m.pattern.test(message))?.tool ?? "unknown";
		return { method: "message-pattern", confidence: 0.6, tool };
	}

	return null;
}

/**
 * Parse git diff --numstat output lines into file list and stats.
 * Handles renames: "old => new" and "{old => new}/file.ts".
 */
export function parseNumstat(lines: string[]): {
	files: string[];
	totalAdd: number;
	totalDel: number;
} {
	const files: string[] = [];
	let totalAdd = 0;
	let totalDel = 0;

	for (const line of lines) {
		const parts = line.split("\t");
		if (parts.length < 3) continue;
		const add = Number.parseInt(parts[0], 10) || 0;
		const del = Number.parseInt(parts[1], 10) || 0;
		totalAdd += add;
		totalDel += del;
		let filePath = parts.slice(2).join("\t");
		// Handle brace renames first: "src/{old => new}/file.ts" → "src/new/file.ts"
		const braceMatch = /\{[^}]*\s*=>\s*([^}]*)\}/.exec(filePath);
		if (braceMatch) {
			filePath = filePath.replace(/\{[^}]*\s*=>\s*[^}]*\}/, braceMatch[1].trim());
		} else {
			// Handle full-path renames: "old/path => new/path"
			const renameMatch = /^(.+?)\s*=>\s*(.+)$/.exec(filePath);
			if (renameMatch) {
				filePath = renameMatch[2].trim();
			}
		}
		files.push(filePath);
	}

	return { files, totalAdd, totalDel };
}

/**
 * Get diff stats for a commit relative to its parent.
 * Returns file list + addition/deletion counts.
 */
async function getDiffStats(
	repoPath: string,
	hash: string,
): Promise<{
	filesChanged: string[];
	diffStat: { additions: number; deletions: number; filesChanged: number };
} | null> {
	const proc = Bun.spawn(["git", "diff", "--numstat", `${hash}^..${hash}`], {
		cwd: repoPath,
		stdout: "pipe",
		stderr: "pipe",
	});

	const exitCode = await proc.exited;
	if (exitCode !== 0) return null;

	const stdout = await new Response(proc.stdout).text();
	const lines = stdout.trim().split("\n").filter(Boolean);

	const parsed = parseNumstat(lines);
	const { files, totalAdd, totalDel } = parsed;

	return {
		filesChanged: files,
		diffStat: {
			additions: totalAdd,
			deletions: totalDel,
			filesChanged: files.length,
		},
	};
}

/**
 * Detect AI-involved commits in a git repository.
 */
export async function detectAICommits(
	repoPath: string,
	options?: { since?: string; until?: string; commit?: string },
): Promise<{
	commits: AICommit[];
	scanned: number;
	skipped: Array<{ hash: string; reason: string }>;
}> {
	const args = ["git", "log", `--format=${GIT_LOG_FORMAT}`];

	if (options?.commit) {
		args.push("-1", options.commit);
	} else {
		if (options?.since) args.push(`--since=${options.since}`);
		if (options?.until) args.push(`--until=${options.until}`);
	}

	const proc = Bun.spawn(args, {
		cwd: repoPath,
		stdout: "pipe",
		stderr: "pipe",
	});

	const exitCode = await proc.exited;
	if (exitCode !== 0) {
		const stderr = await new Response(proc.stderr).text();
		throw new Error(
			`Failed to read git history: ${stderr.trim()}\nMake sure you're in a git repository with at least one commit.`,
		);
	}

	const stdout = await new Response(proc.stdout).text();
	const rawCommits = parseGitLog(stdout);
	const commits: AICommit[] = [];
	const skipped: Array<{ hash: string; reason: string }> = [];

	for (const raw of rawCommits) {
		const signal = detectSignals(raw);
		if (!signal) continue;

		// Check if this is the initial commit (no parent)
		const parentCheck = Bun.spawn(["git", "rev-parse", "--verify", `${raw.hash}^`], {
			cwd: repoPath,
			stdout: "pipe",
			stderr: "pipe",
		});
		const parentExit = await parentCheck.exited;
		if (parentExit !== 0) {
			skipped.push({ hash: raw.shortHash, reason: "no parent commit" });
			continue;
		}

		const diff = await getDiffStats(repoPath, raw.hash);
		if (!diff || diff.filesChanged.length === 0) {
			skipped.push({ hash: raw.shortHash, reason: "empty diff" });
			continue;
		}

		const coAuthors = parseCoAuthors(raw.coAuthorRaw);

		commits.push({
			hash: raw.hash,
			shortHash: raw.shortHash,
			message: raw.subject,
			author: raw.authorEmail,
			coAuthors: coAuthors.map((a) => `${a.name} <${a.email}>`),
			detectionMethod: signal.method,
			detectedTool: signal.tool,
			detectedModel: signal.model,
			confidence: signal.confidence,
			timestamp: new Date(raw.date),
			filesChanged: diff.filesChanged,
			diffStat: diff.diffStat,
		});
	}

	return { commits, scanned: rawCommits.length, skipped };
}
